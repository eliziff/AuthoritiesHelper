// Regenerate the browser distributions of Beaver's one publisher implementation and its one
// matcher for downloaded PDFs. Run from the combined checkout, or pass a Beaver checkout path.
// No network/build of Rust.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {build} from 'esbuild';

const repo=path.resolve(process.argv.find((arg,i)=>i>1&&!arg.startsWith('--'))||path.resolve(import.meta.dirname,'../../..'));
// Hash LF-normalized sources (the committed blobs), so a CRLF checkout verifies the same bundle.
const lf=text=>text.replace(/\r\n/gu,'\n');
for(const [name,entry] of [['publisher.mjs','backend/src/lib/legalSourcePresentation.ts'],['folder.mjs','shared/folder-pdf-match.mjs']]){
  const result=await build({absWorkingDir:repo,entryPoints:[entry],bundle:true,format:'esm',platform:'browser',target:'es2022',write:false,metafile:true});
  const sources=Object.keys(result.metafile.inputs).sort();
  const digest=crypto.createHash('sha256');
  for(const source of sources)digest.update(source).update('\0').update(lf(fs.readFileSync(path.join(repo,source),'utf8')));
  const output=`// Generated by sync-publisher.mjs from Beaver ${entry}. Do not edit.\n// Source SHA-256: ${digest.digest('hex')}\n// See THIRD_PARTY_NOTICES.md.\n${lf(result.outputFiles[0].text)}`;
  const target=path.join(import.meta.dirname,name);
  if(process.argv.includes('--check')){
    if(!fs.existsSync(target)||lf(fs.readFileSync(target,'utf8'))!==output)throw new Error(`${name} is stale. Run sync-publisher.mjs.`);
  }else fs.writeFileSync(target,output);
}
console.log('The publisher and folder bundles match the shared sources.');
